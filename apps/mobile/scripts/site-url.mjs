// Writes www/site.js with the site the app loads, so the no-connection screen can go back to it (run before sync).
import { writeFileSync } from 'node:fs';

const url = process.env.AQUA_APP_URL ?? 'https://app.aqua-swim.co.il';
if (!/^https:\/\/[^/]+$/.test(url))
  throw new Error(`AQUA_APP_URL must be https://<host>, got ${url}`);
writeFileSync(
  new URL('../www/site.js', import.meta.url),
  `// Generated by scripts/site-url.mjs\nwindow.AQUA_SITE_URL = ${JSON.stringify(url)};\n`,
);
console.log(`app loads ${url}`);
